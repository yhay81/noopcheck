import type { AssertClass, CheckResult, FileVerdict, Verdict } from "./core.js";
import type { AuditResult } from "./audit.js";

/** Presentation only — every number here comes from core.ts unchanged. */

const VERDICT_ORDER: Verdict[] = [
  "changed",
  "added",
  "deleted",
  "unverified",
  "value-only",
  "rename-only",
  "format-only",
  "whitespace-only",
  "identical",
];

/**
 * The three tiers a reader actually cares about.
 *
 * `attention` (in core) is one fail-closed bucket, which is the right shape
 * for a gate but the wrong shape for a human: it puts "the logic moved" and
 * "a string literal moved" in the same list. A translation sweep is mostly
 * the latter, and saying "read all 28" there wastes exactly the attention
 * this tool exists to save. So the display splits what the engine already
 * distinguishes — without ever moving a file down a tier it does not belong
 * in.
 */
export function tiers(result: CheckResult): {
  read: FileVerdict[];
  skim: FileVerdict[];
  skipped: FileVerdict[];
} {
  const read: FileVerdict[] = [];
  const skim: FileVerdict[] = [];
  const skipped: FileVerdict[] = [];
  for (const f of result.files) {
    if (f.verdict === "rename-only" || f.verdict === "value-only") skim.push(f);
    else if (result.attention.includes(f)) read.push(f);
    else skipped.push(f);
  }
  return { read, skim, skipped };
}

export function summarize(result: CheckResult): string {
  const counts = new Map<Verdict, number>();
  for (const f of result.files)
    counts.set(f.verdict, (counts.get(f.verdict) ?? 0) + 1);
  const parts = VERDICT_ORDER.filter((v) => counts.has(v)).map(
    (v) => `${String(counts.get(v))} ${v}`,
  );
  return `${String(result.files.length)} files: ${parts.join(", ")}`;
}

/**
 * PR-comment / job-summary Markdown.
 *
 * Silence is the default output: when every file fits the declared class
 * there is a single line saying so, not a scorecard. The point of the
 * report is the "read these N" list — everything else is context for it.
 */
export function renderMarkdown(
  result: CheckResult,
  declared: AssertClass | undefined,
  failing: FileVerdict[],
): string {
  const lines: string[] = ["## noopcheck", ""];
  lines.push(
    `\`${result.base}...${result.head}\` — ${summarize(result)}`,
    "",
  );

  if (declared !== undefined) {
    if (failing.length === 0) {
      lines.push(
        `✅ Every file fits the declared change class **${declared}**.`,
      );
    } else {
      lines.push(
        `❌ ${String(failing.length)} file(s) exceed the declared class **${declared}**:`,
        "",
        "| file | verdict |",
        "| --- | --- |",
        ...failing.map((f) => `| \`${f.path}\` | ${f.verdict} |`),
      );
    }
  } else if (result.attention.length === 0) {
    lines.push(
      "✅ Nothing beyond formatting-level changes — no file needs reading for behaviour.",
    );
  } else {
    const { read, skim, skipped } = tiers(result);
    const table = (files: FileVerdict[]): string[] => [
      "",
      "| file | verdict |",
      "| --- | --- |",
      ...files.map((f) => `| \`${f.path}\` | ${f.verdict} |`),
      "",
    ];
    if (read.length > 0) {
      lines.push(
        `**Read these ${String(read.length)} of ${String(result.files.length)}** — the structure moved:`,
        ...table(read),
      );
    }
    if (skim.length > 0) {
      lines.push(
        `**Skim these ${String(skim.length)}** — same structure, only identifiers or literal values moved:`,
        ...table(skim),
      );
    }
    if (skipped.length > 0) {
      lines.push(
        `<sub>The other ${String(skipped.length)} file(s) are identical, format-only, or whitespace-only at the AST level.</sub>`,
      );
    }
  }

  lines.push(
    "",
    "<sub>Verdicts come from comparing the syntax tree of each revision, not the line diff." +
      " Structural equivalence is not semantic equivalence: this reports the change class, it does not certify safety." +
      " Generated by [noopcheck](https://github.com/yhay81/noopcheck).</sub>",
  );
  return lines.join("\n");
}

export function renderAudit(result: AuditResult, range: string): string[] {
  const lines: string[] = [];
  if (result.scanned === 0) {
    lines.push(
      `No commits in ${range} declared themselves mechanical (style:, refactor:, chore(deps):, …), so there was no claim to check.`,
    );
    return lines;
  }

  const conforming = result.entries.filter((e) => e.conforming).length;
  const pct = Math.round((conforming / result.scanned) * 100);
  lines.push(
    `${String(result.scanned)} commits in ${range} declared themselves mechanical.`,
    `${String(conforming)} of them (${String(pct)}%) really were no-ops of the class they declared.`,
    "",
  );
  if (result.commitsWithNothingVerifiable > 0) {
    lines.push(
      `  (${String(result.commitsWithNothingVerifiable)} of those touched no TypeScript at all —` +
        ` lockfiles, docs, and CI config carry no verdict, so they count as conforming by default.)`,
      "",
    );
  }
  for (const cls of ["format", "rename", "value"] as const) {
    const s = result.byClass[cls];
    if (s.total === 0) continue;
    lines.push(
      `  ${cls.padEnd(7)} ${String(s.conforming)}/${String(s.total)} conforming`,
    );
  }

  const offenders = result.entries.filter((e) => !e.conforming);
  if (offenders.length > 0) {
    lines.push(
      "",
      `These ${String(offenders.length)} changed more than their subject line says — a reviewer reading only the subject would not have known to look:`,
      "",
    );
    for (const e of offenders.slice(0, 15)) {
      lines.push(`  ${e.sha.slice(0, 8)}  ${e.subject.slice(0, 60)}`);
      lines.push(
        `    declared ${e.declared}, but ${e.offenders
          .map((o) => `${o.path} (${o.verdict})`)
          .join(", ")}`,
      );
    }
    if (offenders.length > 15) {
      lines.push(`  … and ${String(offenders.length - 15)} more`);
    }
  }
  return lines;
}
